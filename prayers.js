// Visit every prayer before repeating; chosen situations are never persisted.
function createPrayerPicker(library, random = Math.random) {
  const history = new Map();
  return function next(topic) {
    if (!Object.hasOwn(library, topic)) topic = 'General';
    const guide = library[topic];
    let state = history.get(topic);
    if (!state) { state = { bag: [], last: -1 }; history.set(topic, state); }
    if (state.bag.length === 0) {
      state.bag = guide.prayers.map((_, index) => index);
      for (let index = state.bag.length - 1; index > 0; index--) {
        const swap = Math.floor(random() * (index + 1));
        [state.bag[index], state.bag[swap]] = [state.bag[swap], state.bag[index]];
      }
      const end = state.bag.length - 1;
      if (end > 0 && state.bag[end] === state.last) [state.bag[0], state.bag[end]] = [state.bag[end], state.bag[0]];
    }
    const index = state.bag.pop();
    state.last = index;
    const prayer = guide.prayers[index];
    const catalogId = `written-v1-${topic.toLowerCase()}-${index + 1}`;
    return { id: catalogId, catalogId, index, topic, title: prayer.title, thought: prayer.thought,
      prayer: prayer.text, source: 'written', scripture: { reference: guide.reference, thought: guide.reflection } };
  };
}
